// Rebuild the offline image map from the checked-in WebP files. No network needed.
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assetDir = path.join(root, 'src/assets/tarot');
const manifest = JSON.parse(await readFile(path.join(assetDir, 'assets-sources.json'), 'utf8'));
const expected = [
  ...Array.from({ length: 22 }, (_, n) => `major-${String(n).padStart(2, '0')}`),
  ...['wands', 'cups', 'swords', 'pentacles'].flatMap(suit =>
    Array.from({ length: 14 }, (_, n) => `${suit}-${String(n + 1).padStart(2, '0')}`)),
];
const files = (await readdir(assetDir)).filter(name => name.endsWith('.webp')).sort();
const entries = new Map(manifest.cards.map(card => [card.id, card]));
if (manifest.cards.length !== 78 || entries.size !== 78 || files.length !== 78) {
  throw new Error('Tarot assets must contain exactly 78 unique cards.');
}
const assets = {};
let byteCount = 0;
for (const id of expected) {
  const card = entries.get(id);
  if (!card || card.license.shortName !== 'Public domain') throw new Error(`Missing provenance for ${id}`);
  const bytes = await readFile(path.join(assetDir, `${id}.webp`));
  if (bytes.toString('ascii', 0, 4) !== 'RIFF' || bytes.toString('ascii', 8, 12) !== 'WEBP') {
    throw new Error(`Invalid WebP container for ${id}`);
  }
  if (createHash('sha256').update(bytes).digest('hex') !== card.asset.sha256) {
    throw new Error(`Tarot asset SHA-256 mismatch for ${id}`);
  }
  byteCount += bytes.length;
  assets[id] = `data:image/webp;base64,${bytes.toString('base64')}`;
}
const output = '// Generated by scripts/build-tarot-assets.mjs. 78 historical Pam-A scans.\n'
  + '// Per-card provenance and public-domain declarations: src/assets/tarot/assets-sources.json\n'
  + `export const tarotAssets: Record<string, string> = ${JSON.stringify(assets, null, 2)};\n`;
await writeFile(path.join(root, 'src/client/tarot-assets.ts'), output);
console.log(`Verified and embedded ${expected.length} Tarot WebP images (${byteCount} bytes).`);
